import Joi from 'joi';

export const createSchoolConfigSchema = Joi.object({
  schoolNameEn: Joi.string().trim().max(255).required().messages({
    'string.empty': 'School name in English is required',
    'string.max': 'School name must not exceed 255 characters',
  }),
  schoolNameNp: Joi.string().trim().max(255).required(),
  schoolCode: Joi.string().trim().max(50).required(),
  logoUrl: Joi.string().max(500).optional().allow(''),
  addressEn: Joi.string().trim().required(),
  addressNp: Joi.string().trim().required(),
  city: Joi.string().trim().max(100).required(),
  district: Joi.string().trim().max(100).required(),
  province: Joi.string().trim().max(100).required(),
  postalCode: Joi.string().max(20).optional().allow(''),
  establishedYear: Joi.number().integer().min(1).max(9999).optional(),
  affiliationNumber: Joi.string().max(100).optional().allow(''),
  principalName: Joi.string().max(255).optional().allow(''),
  principalNameNp: Joi.string().max(255).optional().allow(''),
  primaryColor: Joi.string().pattern(/^#[0-9a-fA-F]{6}$/).optional(),
  secondaryColor: Joi.string().pattern(/^#[0-9a-fA-F]{6}$/).optional(),
  accentColor: Joi.string().pattern(/^#[0-9a-fA-F]{6}$/).optional(),
  phone: Joi.string().trim().min(7).max(20).required(),
  email: Joi.string().trim().email().max(255).required(),
  website: Joi.string().uri().max(255).optional().allow(''),
  academicYearStartMonth: Joi.number().integer().min(1).max(12).optional(),
  academicYearDurationMonths: Joi.number().integer().min(1).max(12).optional(),
  termsPerYear: Joi.number().integer().min(1).max(4).optional(),
  defaultCalendarSystem: Joi.string().valid('BS', 'AD').optional(),
  defaultLanguage: Joi.string().valid('nepali', 'english').optional(),
  timezone: Joi.string().max(50).optional(),
  currency: Joi.string().max(10).optional(),
  dateFormat: Joi.string().max(50).optional(),
  timeFormat: Joi.string().max(50).optional(),
  numberFormat: Joi.string().max(50).optional(),
});

